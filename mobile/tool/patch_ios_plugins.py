#!/usr/bin/env python3
"""Apply reviewed native fixes to build-local Swift packages, never pub cache.

build_ios.sh runs this before Xcode resolves packages. Transient path overrides
ensure Xcode compiles the local copies rather than canonicalizing shared-cache
symlinks during build planning. Reviewed source hashes guard every edit.
"""

import json
import hashlib
import argparse
from pathlib import Path
import shutil
import tempfile
from urllib.parse import unquote, urlparse


def patched_sources(package, patches):
    """Validate every edit before changing any source in this package."""
    sources = {}
    for patch in patches:
        relative = Path(patch["file"])
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError(f"Invalid patch path: {relative}")
        source = package / relative
        text = source.read_text()
        digest = hashlib.sha256(text.encode()).hexdigest()
        if digest == patch["after_sha256"]:
            continue
        if digest != patch["before_sha256"]:
            raise ValueError(f"Unreviewed source in {source}; review the upstream update")
        original = text
        for replacement in patch["replacements"]:
            before, after = replacement["before"], replacement["after"]
            if before and before in text:
                text = text.replace(before, after)
            else:
                raise ValueError(f"Patch context changed in {source}; review the upstream update")
        if hashlib.sha256(text.encode()).hexdigest() != patch["after_sha256"]:
            raise ValueError(f"Patched source hash mismatch in {source}")
        if text != original:
            sources[relative] = text
    return sources


def patch_package(package, patches):
    edits = patched_sources(package, patches)
    if not edits:
        return 0
    # Flutter's .packages entries point at a shared cache. Materialize a local
    # copy first; writes must never pass through that link into another app.
    if package.is_symlink():
        with tempfile.TemporaryDirectory(dir=package.parent) as temporary:
            local = Path(temporary) / "package"
            shutil.copytree(package.resolve(), local, symlinks=False)
            for relative, content in edits.items():
                (local / relative).write_text(content)
            package.unlink()
            local.rename(package)
    else:
        for relative, content in edits.items():
            source = package / relative
            if not source.resolve().is_relative_to(package.resolve()):
                raise ValueError(f"Refusing to write through external source link: {source}")
            source.write_text(content)
    return len(edits)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="Validate pinned cache sources without editing them")
    mode.add_argument("--prepare", action="store_true", help="Prepare local copies and transient pub overrides")
    args = parser.parse_args()
    mobile = Path(__file__).resolve().parents[1]
    patches = json.loads(Path(__file__).with_name("ios_plugin_patches.json").read_text())
    config_file = mobile / ".dart_tool/package_config.json"
    config = json.loads(config_file.read_text())
    dependencies = {p["name"]: p for p in config["packages"]}
    overrides_file = mobile / "pubspec_overrides.yaml"
    if args.prepare and overrides_file.exists():
        raise SystemExit("Refusing to overwrite an existing pubspec_overrides.yaml")
    overrides = ["# Generated by tool/build_ios.sh; removed after building.", "dependency_overrides:"]
    for name, changes in patches.items():
        plugin = name.rsplit("-", 1)[0]
        uri = urlparse(dependencies[plugin]["rootUri"])
        if uri.scheme not in ("", "file"):
            raise ValueError(f"Unsupported package URI: {uri.scheme}")
        source = Path(unquote(uri.path))
        if not source.is_absolute():
            source = config_file.parent / source
        platform = "darwin" if plugin in ("sentry_flutter", "posthog_flutter") else "ios"
        patched_sources(source / platform / plugin, changes)
        if args.prepare:
            local = mobile / ".native_plugins" / name
            if source.resolve() == local.resolve():
                raise SystemExit("Run flutter pub get without overrides before preparing again")
            if local.exists():
                shutil.rmtree(local)
            shutil.copytree(source, local, ignore=shutil.ignore_patterns("example", "test", ".dart_tool", "build"))
            patch_package(local / platform / plugin, changes)
            pubspec = local / "pubspec.yaml"
            pubspec.write_text(pubspec.read_text().replace("resolution: workspace\n", ""))
            overrides.extend([f"  {plugin}:", f"    path: .native_plugins/{name}"])
    if args.prepare:
        overrides_file.write_text("\n".join(overrides) + "\n")
        print(f"Prepared {len(patches)} corrected local packages before Xcode build planning")
    else:
        print(f"Reviewed patch contexts match all {len(patches)} pinned packages; shared cache unchanged")


if __name__ == "__main__":
    main()
